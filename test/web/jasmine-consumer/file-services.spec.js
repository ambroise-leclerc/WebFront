// Qualification of the file services every engine must give a page without any native API (issue #451): files reach the
// page as File objects, a generated Blob can be offered for download, and the page keeps working afterwards.
describe('File services in the embedded engine', () => {
    let host;
    beforeEach(() => {
        host = document.createElement('section');
        document.body.append(host);
    });
    afterEach(() => host.remove());

    it('reads the content of files given to an <input type="file"> and to a drop', async () => {
        const {step, event} = webFrontTestAsync.steps();
        const input = document.createElement('input');
        input.type = 'file';
        input.multiple = true;
        host.append(input);
        const transfer = new DataTransfer();
        transfer.items.add(new File(['first file'], 'first.txt', {type: 'text/plain'}));
        transfer.items.add(new File([new Uint8Array([1, 2, 3, 255])], 'second.bin'));
        await event(input, 'change', () => {
            input.files = transfer.files;
            input.dispatchEvent(new Event('change', {bubbles: true}));
        });
        expect(input.files.length).toBe(2);
        expect(await step('first.txt text()', () => input.files[0].text())).toBe('first file');
        expect(Array.from(new Uint8Array(await step('second.bin arrayBuffer()', () => input.files[1].arrayBuffer())))).toEqual([1, 2, 3, 255]);
        const summary = document.createElement('p');
        summary.textContent = Array.from(input.files, file => `${file.name} (${file.size} bytes)`).join(', ');
        host.append(summary);
        expect(await step('screenshot(file-input)', () => webFrontCapture.screenshot('file-input'))).toBeGreaterThan(100);
    }, webFrontTestAsync.specTimeoutMs);

    it('accepts the directory flag and the accept filter on the input', () => {
        const input = document.createElement('input');
        input.type = 'file';
        input.accept = '.txt,image/*';
        input.webkitdirectory = true;
        host.append(input);
        expect(input.accept).toBe('.txt,image/*');
        expect(input.webkitdirectory).toBe(true);
    });

    it('offers a generated Blob for download without breaking the page or the bridge', async () => {
        const {step} = webFrontTestAsync.steps();
        const link = document.createElement('a');
        link.href = URL.createObjectURL(new Blob(['generated by the page'], {type: 'text/plain'}));
        link.download = 'generated.txt';
        link.textContent = 'generated.txt';
        host.append(link);
        try {
            link.click();
            await step('settle after download click', () => new Promise(resolve => setTimeout(resolve, 500)));
            expect(location.protocol).toMatch(/^https?:$/);  // The window stayed on the application.
            expect(await step('consumer.answer after download', () => webFront.cppFunction('consumer.answer')())).toBe(42);
            expect(await step('screenshot(download-link)', () => webFrontCapture.screenshot('download-link'))).toBeGreaterThan(100);
        } finally {
            URL.revokeObjectURL(link.href);
        }
    }, webFrontTestAsync.specTimeoutMs);
});
