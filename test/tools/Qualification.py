#!/usr/bin/env python3
"""Qualification report of the file services of the embedded frontends (issue #451).

Two steps, both pure standard library:

  Qualification.py collect --build DIR --evidence DIR --platform NAME --output DIR
      Gathers, on one CI platform, the CTest results of the file-service tests, the captures the specs wrote and the
      evidence of the native scenarios (WEBFRONT_QUALIFICATION_DIR) into one folder with a manifest.

  Qualification.py report --input DIR --output FILE
      Assembles the manifests of every platform (one sub-folder each) into a Markdown document that embeds the captures.
      A platform that did not report, or a scenario nobody ran, is written as such rather than left out.
"""
import argparse
import datetime
import json
import pathlib
import shutil
import sys
import xml.etree.ElementTree as ET

# Scenario -> (title, what it proves). The CTest names carry the platform-independent part.
GENERIC = ("ConsumerJasmine-file-services", "Files and Blob download offered to the page (File API, `<input type=file>`, `<a download>`)")
NATIVE = {
    "choose-file": "`<input type=file>`: the chooser answers with a fixture file, the page reads it",
    "cancel-choose": "`<input type=file>`: cancelling the chooser emits `cancel`, no error",
    "download": "`<a download>` of a generated Blob lands in the download folder, inside it",
}
NATIVE_TESTS = {  # engine -> CTest name pattern of a native scenario
    "WebKitGTK": "WebKitGTKAdapter-{}",
    "CEF": {"choose-file": "CEFFileServices-choose", "cancel-choose": "CEFFileServices-cancel", "download": "CEFFileServices-download"},
}
ENGINES = ["WebKitGTK", "CEF", "WKWebView", "WebView2"]
NOT_INJECTED = {
    "WKWebView": "chooser and download are implemented (`runOpenPanelWithParameters`, `WKDownloadDelegate`) with a test injection, but no native scenario drives them yet",
    "WebView2": "the engine's own chooser and download UI are used; no injection point exists yet",
}


def engine_of(platform: str) -> str:
    lowered = platform.lower()
    for engine in ENGINES:
        if engine.lower() in lowered:
            return engine
    return platform


def junit_results(build: pathlib.Path) -> dict[str, str]:
    results: dict[str, str] = {}
    for path in sorted(build.glob("test-results-*.xml")) + sorted(build.glob("test-results.xml")):
        for case in ET.parse(path).getroot().iter("testcase"):
            name = case.get("name", "")
            if "file-services" not in name and "FileServices" not in name and not name.startswith("WebKitGTKAdapter-"):
                continue
            if case.find("failure") is not None or case.find("error") is not None:
                status = "failed"
            elif case.find("skipped") is not None:
                status = "skipped"
            else:
                status = "passed"
            # Several passes (repeated runs): any failure wins.
            if results.get(name) != "failed":
                results[name] = status
    return results


def collect(args: argparse.Namespace) -> int:
    build, out = pathlib.Path(args.build), pathlib.Path(args.output)
    out.mkdir(parents=True, exist_ok=True)
    manifest = {"platform": args.platform, "engine": engine_of(args.platform), "tests": junit_results(build), "images": []}
    sources = [(p, "spec") for p in build.glob("test/web/webfront-jasmine/ConsumerJasmine-file-services/captures/*.png")]
    evidence = pathlib.Path(args.evidence) if args.evidence else None
    if evidence and evidence.is_dir():
        sources += [(p, "native") for p in evidence.glob("*.png")]
    for source, kind in sources:
        target = f"{kind}-{source.name}"
        shutil.copyfile(source, out / target)
        manifest["images"].append({"file": target, "kind": kind, "name": source.stem})
    if evidence and evidence.is_dir():
        manifest["native"] = [json.loads(p.read_text()) for p in sorted(evidence.glob("*.json"))]
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"{args.platform}: {len(manifest['tests'])} results, {len(manifest['images'])} captures")
    return 0


def native_test(engine: str, scenario: str):
    entry = NATIVE_TESTS.get(engine)
    if isinstance(entry, str):
        return entry.format(scenario)
    return entry.get(scenario) if entry else None


def mark(status):
    return {"passed": "✅ passed", "failed": "❌ failed", "skipped": "⏭ skipped"}.get(status, "⚪ not run")


def report(args: argparse.Namespace) -> int:
    root, out = pathlib.Path(args.input), pathlib.Path(args.output)
    manifests = {}
    for path in sorted(root.glob("*/manifest.json")):
        data = json.loads(path.read_text())
        manifests[path.parent.name] = (path.parent, data)
    out.parent.mkdir(parents=True, exist_ok=True)
    images = out.parent / "images"
    images.mkdir(exist_ok=True)
    lines = ["# Qualification of the file services of the embedded frontends", "",
             f"Generated by CI on {datetime.date.today().isoformat()} from the run's platform artifacts (issue #451). "
             "Captures are taken by WebFront's own window capture (`webfront::frontend::capturePng`): web content only, "
             "native dialogs are not part of them.", "",
             "## Summary", "", "| Platform | Engine | Spec: files and Blob download | " + " | ".join(NATIVE.values()) + " |",
             "| --- | --- | --- | " + " | ".join("---" for _ in NATIVE) + " |"]
    for name, (_, data) in manifests.items():
        engine = data["engine"]
        row = [name, engine, mark(data["tests"].get(GENERIC[0]))]
        for scenario in NATIVE:
            test = native_test(engine, scenario)
            row.append(mark(data["tests"].get(test)) if test else "⚪ not injected")
        lines.append("| " + " | ".join(row) + " |")
    missing = [e for e in ENGINES if not any(d["engine"] == e for _, d in manifests.values())]
    if missing:
        lines += ["", "No report from: " + ", ".join(missing) + " (the job did not run in this workflow, or failed before reporting)."]
    lines += ["", "## Limits by engine", ""]
    for engine, reason in NOT_INJECTED.items():
        lines.append(f"- **{engine}**: {reason}.")
    lines.append("- **CEF** (Chrome runtime) and **WebKitGTK**: native dialog and download handling, plus a test injection answering without a dialog.")
    for name, (folder, data) in manifests.items():
        lines += ["", f"## {name} ({data['engine']})", ""]
        for image in data["images"]:
            shutil.copyfile(folder / image["file"], images / f"{name}-{image['file']}")
            lines += [f"**{image['name']}** ({'spec capture' if image['kind'] == 'spec' else 'native scenario'})", "",
                      f"![{name} {image['name']}](images/{name}-{image['file']})", ""]
        if not data["images"]:
            lines.append("No capture was produced.")
        failed = [t for t, s in data["tests"].items() if s == "failed"]
        if failed:
            lines += ["", "Failed: " + ", ".join(f"`{t}`" for t in failed)]
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(manifests)} platforms)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    c = sub.add_parser("collect")
    c.add_argument("--build", required=True)
    c.add_argument("--evidence")
    c.add_argument("--platform", required=True)
    c.add_argument("--output", required=True)
    r = sub.add_parser("report")
    r.add_argument("--input", required=True)
    r.add_argument("--output", required=True)
    args = parser.parse_args()
    return collect(args) if args.command == "collect" else report(args)


if __name__ == "__main__":
    sys.exit(main())
